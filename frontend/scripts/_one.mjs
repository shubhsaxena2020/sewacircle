import { chromium } from 'playwright'
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errs = []; p.on('console', m => { if (m.type() !== 'log') errs.push(m.type() + ': ' + m.text().slice(0, 140)) })
await p.goto('http://127.0.0.1:5181/'); await p.waitForTimeout(1500); await p.mouse.move(700, 400); await p.waitForTimeout(5000)
await p.screenshot({ path: '../docs/screens/v6/_intro.png' })
await p.evaluate(() => document.getElementById('crew').scrollIntoView({ block: 'center' })); await p.waitForTimeout(1500)
await p.getByRole('button', { name: 'Plan the crew' }).click(); await p.waitForTimeout(4500)
await p.mouse.move(1250, 300); await p.waitForTimeout(300)
const lab = p.locator('.seat-label.s-filled').first(); await lab.hover().catch(() => {}); await p.waitForTimeout(1200)
await p.screenshot({ path: '../docs/screens/v6/_crew.png' })
await p.evaluate(() => document.getElementById('numbers').scrollIntoView({ block: 'center' })); await p.waitForTimeout(4000)
await p.screenshot({ path: '../docs/screens/v6/_numbers.png' })
console.log(errs.slice(0, 8)); await b.close()
